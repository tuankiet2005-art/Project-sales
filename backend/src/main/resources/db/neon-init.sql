DROP TABLE IF EXISTS fee_rules CASCADE;
DROP TABLE IF EXISTS vehicles CASCADE;
DROP TABLE IF EXISTS fee_definitions CASCADE;
DROP TABLE IF EXISTS locations CASCADE;
DROP TABLE IF EXISTS vehicle_categories CASCADE;
DROP TABLE IF EXISTS dealers CASCADE;
DROP TABLE IF EXISTS brands CASCADE;

CREATE TABLE brands (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(40)  NOT NULL UNIQUE,
    name            VARCHAR(80)  NOT NULL,
    tagline         VARCHAR(240),
    market          VARCHAR(80)  NOT NULL,
    accent_color    VARCHAR(16),
    image_url       VARCHAR(1000),
    ready           BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order      INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE vehicle_categories (
    id                                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                              VARCHAR(64)  NOT NULL UNIQUE,
    name                              VARCHAR(120) NOT NULL,
    description                       VARCHAR(500),
    typical_seats                     INTEGER,
    requires_inspection               BOOLEAN NOT NULL DEFAULT FALSE,
    requires_road_use_fee             BOOLEAN NOT NULL DEFAULT FALSE,
    requires_compulsory_insurance     BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order                        INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE locations (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                      VARCHAR(32)  NOT NULL UNIQUE,
    name                      VARCHAR(160) NOT NULL,
    name_en                   VARCHAR(160) NOT NULL,
    name_zh                   VARCHAR(160) NOT NULL,
    name_ja                   VARCHAR(160) NOT NULL,
    region                    VARCHAR(32)  NOT NULL,
    fee_zone                  VARCHAR(32)  NOT NULL,
    centrally_governed_city   BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE dealers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id    BIGINT NOT NULL REFERENCES brands (id),
    name        VARCHAR(200) NOT NULL,
    address     VARCHAR(400),
    market      VARCHAR(80) NOT NULL DEFAULT 'Vietnam',
    active      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE fee_definitions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(64)  NOT NULL UNIQUE,
    name          VARCHAR(160) NOT NULL,
    description   VARCHAR(500),
    mandatory     BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order    INTEGER      NOT NULL DEFAULT 0,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE vehicles (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id                    BIGINT NOT NULL REFERENCES brands (id),
    category_id                 BIGINT NOT NULL REFERENCES vehicle_categories (id),
    model                       VARCHAR(80)  NOT NULL,
    name                        VARCHAR(180) NOT NULL,
    seats                       INTEGER,
    vehicle_type                VARCHAR(40),
    model_year                  INTEGER,
    engine_cc                   INTEGER,
    fuel_type                   VARCHAR(40),
    transmission                VARCHAR(40),
    list_price                  NUMERIC(18,2) NOT NULL,
    discount_amount             NUMERIC(18,2),
    sale_price                  NUMERIC(18,2),
    tax_base_price              NUMERIC(18,2),
    default_deposit             NUMERIC(18,2),
    registration_service_fee    NUMERIC(18,2),
    mica_plate_fee              NUMERIC(18,2),
    inspection_fee              NUMERIC(18,2),
    default_color               VARCHAR(80),
    available_colors            VARCHAR(240),
    delivery_note               VARCHAR(120),
    warranty_note               VARCHAR(400),
    gifts                       TEXT,
    quote_sheet_name            VARCHAR(80),
    image_url                   VARCHAR(1000),
    specifications              TEXT,
    active                      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE fee_rules (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_definition_id   BIGINT NOT NULL REFERENCES fee_definitions (id),
    category_id         BIGINT REFERENCES vehicle_categories (id),
    location_id         BIGINT REFERENCES locations (id),
    fee_zone            VARCHAR(32),
    calculation_type    VARCHAR(40) NOT NULL,
    fixed_amount        NUMERIC(18,2),
    percentage          NUMERIC(8,4),
    min_amount          NUMERIC(18,2),
    max_amount          NUMERIC(18,2),
    min_engine_cc       INTEGER,
    max_engine_cc       INTEGER,
    min_price           NUMERIC(18,2),
    max_price           NUMERIC(18,2),
    priority            INTEGER NOT NULL DEFAULT 0,
    effective_from      DATE,
    effective_to        DATE,
    active              BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_vehicles_brand ON vehicles (brand_id);
CREATE INDEX idx_vehicles_category ON vehicles (category_id);
CREATE INDEX idx_fee_rules_definition ON fee_rules (fee_definition_id);

